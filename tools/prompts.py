"""Generate and check the prompt documentation.

`controller/tools.json` is the single source of truth for the command
catalogue. This script renders it into `prompts/tool-catalogue.md` and, with
`--check`, verifies that the prompt documentation still matches the code the
extension actually ships.

Usage:
    python3 tools/prompts.py            # rewrite prompts/tool-catalogue.md
    python3 tools/prompts.py --check    # exit 1 on drift (safe for CI-less use)
    python3 tools/prompts.py --stdout   # print the catalogue, write nothing
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TOOLS_JSON = ROOT / "controller" / "tools.json"
CONFIG_JS = ROOT / "extension" / "core" / "config.js"
CATALOGUE_MD = ROOT / "prompts" / "tool-catalogue.md"
RULES_MD = ROOT / "prompts" / "agent-rules.md"
SYSTEM_MD = ROOT / "prompts" / "system-prompt.md"

HEADER = """# Tool catalogue (generated)

<!-- Generated by tools/prompts.py from controller/tools.json. Do not edit by hand. -->
<!-- Run `python3 tools/prompts.py` after changing tools.json. -->

{count} commands, grouped the way the system prompt presents them. `?` marks an
optional parameter; everything else is required.

"""

GROUP_TITLES = {
    "read": "Inspect / read",
    "edit": "Files",
    "scene": "Scene and scripts",
    "run": "Project and run",
    "tool": "Meta",
}

# Phrases that must exist in the extension's prompt code: the documentation in
# prompts/ promises them, so a missing one means the docs drifted from the code.
CONFIG_MARKERS = [
    "###GDSCRIPT###",
    "###CSHARP###",
    "###LUA###",
    "attach_script",
    "Never write two commands in one reply",
    "C# available",
    "res://",
    "NonZeroScript",
]

RULES_MARKERS = [
    "###GDSCRIPT###",
    "###CSHARP###",
    "attach_script",
    "one command",
]


def load_tools() -> list[dict]:
    data = json.loads(TOOLS_JSON.read_text(encoding="utf-8"))
    tools = data.get("tools")
    if not isinstance(tools, list) or not tools:
        raise SystemExit("tools.json has no tools")
    return tools


def render() -> str:
    tools = load_tools()
    out = [HEADER.format(count=len(tools))]
    seen: list[str] = []
    for tool in tools:
        group = str(tool.get("category") or "tool")
        if group not in seen:
            seen.append(group)
    for group in seen:
        title = GROUP_TITLES.get(group, group.title())
        out.append(f"## {title}\n\n")
        out.append("| Command | Parameters |\n|---|---|\n")
        for tool in tools:
            if str(tool.get("category") or "tool") != group:
                continue
            params = tool.get("params") or {}
            args = ", ".join(
                f"`{name}`" if (spec or {}).get("required") else f"`{name}?`"
                for name, spec in params.items()
            ) or "—"
            out.append(f"| `{tool['name']}` | {args} |\n")
        out.append("\n")
        for tool in tools:
            if str(tool.get("category") or "tool") != group:
                continue
            out.append(f"### `{tool['name']}`\n\n")
            out.append(f"{(tool.get('description') or '').strip()}\n\n")
            params = tool.get("params") or {}
            if params:
                out.append("| Parameter | Type | Required | Description |\n|---|---|---|---|\n")
                for name, spec in params.items():
                    spec = spec or {}
                    out.append(
                        "| `{}` | {} | {} | {} |\n".format(
                            name,
                            spec.get("type", "any"),
                            "yes" if spec.get("required") else "no",
                            str(spec.get("description", "")).replace("|", "\\|"),
                        )
                    )
                out.append("\n")
    return "".join(out)


def check() -> list[str]:
    problems: list[str] = []
    expected = render()
    if not CATALOGUE_MD.exists():
        problems.append("prompts/tool-catalogue.md is missing (run tools/prompts.py)")
    elif CATALOGUE_MD.read_text(encoding="utf-8") != expected:
        problems.append("prompts/tool-catalogue.md is out of date (run tools/prompts.py)")

    config = CONFIG_JS.read_text(encoding="utf-8") if CONFIG_JS.exists() else ""
    if not config:
        problems.append("extension/core/config.js is missing")
    for marker in CONFIG_MARKERS:
        if marker not in config:
            problems.append(f"config.js no longer mentions {marker!r} (docs promise it)")

    rules = RULES_MD.read_text(encoding="utf-8").lower() if RULES_MD.exists() else ""
    if not rules:
        problems.append("prompts/agent-rules.md is missing")
    for marker in RULES_MARKERS:
        if marker.lower() not in rules:
            problems.append(f"prompts/agent-rules.md no longer mentions {marker!r}")

    system = SYSTEM_MD.read_text(encoding="utf-8") if SYSTEM_MD.exists() else ""
    if not system:
        problems.append("prompts/system-prompt.md is missing")
    for placeholder in ("{{ENVIRONMENT}}", "{{TOOL_CATALOGUE}}", "{{SYS_MARKER}}"):
        if placeholder not in system:
            problems.append(f"prompts/system-prompt.md lost {placeholder}")

    return problems


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="Generate/check the prompt documentation")
    ap.add_argument("--check", action="store_true", help="verify, do not write")
    ap.add_argument("--stdout", action="store_true", help="print the catalogue")
    args = ap.parse_args(argv)

    text = render()
    if args.stdout:
        sys.stdout.write(text)
        return 0
    if args.check:
        problems = check()
        if problems:
            for p in problems:
                print(f"FAIL {p}")
            print(f"\n{len(problems)} problem(s). Run: python3 tools/prompts.py")
            return 1
        print(f"OK prompt docs match tools.json ({len(load_tools())} commands) and config.js")
        return 0

    CATALOGUE_MD.parent.mkdir(parents=True, exist_ok=True)
    CATALOGUE_MD.write_text(text, encoding="utf-8")
    print(f"wrote {CATALOGUE_MD.relative_to(ROOT)} ({len(load_tools())} commands)")
    problems = check()
    for p in problems:
        print(f"warn {p}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
